-- Additive migration. Existing data and business rules are unchanged.
BEGIN;
CREATE TABLE IF NOT EXISTS audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL,
    actor_name VARCHAR(150) NOT NULL,
    actor_role VARCHAR(20) NOT NULL,
    action VARCHAR(40) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    target_id BIGINT NOT NULL,
    before_data TEXT NOT NULL,
    after_data TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
-- Actor snapshot intentionally has no cascading foreign key: account deletion must not erase history.
CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_logs(created_at,id);
CREATE INDEX IF NOT EXISTS idx_audit_actor_role ON audit_logs(actor_role,created_at);
COMMIT;
