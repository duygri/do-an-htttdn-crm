-- Bảng mới: vận chuyển
CREATE TABLE IF NOT EXISTS shipping_carriers (
    code VARCHAR(30) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    tracking_url_template VARCHAR(300),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS shipments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES orders(order_id),
    carrier_code VARCHAR(30) NOT NULL REFERENCES shipping_carriers(code),
    tracking_code VARCHAR(120) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'CREATED'
        CHECK (status IN ('CREATED','PICKED_UP','IN_TRANSIT','OUT_FOR_DELIVERY','DELIVERED','FAILED','RETURNED')),
    note VARCHAR(1000),
    shipped_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS shipment_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT NOT NULL REFERENCES shipments(id),
    status VARCHAR(30) NOT NULL
        CHECK (status IN ('CREATED','PICKED_UP','IN_TRANSIT','OUT_FOR_DELIVERY','DELIVERED','FAILED','RETURNED')),
    note VARCHAR(1000),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_shipment_events_shipment ON shipment_events(shipment_id,id);

-- Bảng mới: đổi trả theo sản phẩm
CREATE TABLE IF NOT EXISTS order_return_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    order_item_id BIGINT NOT NULL REFERENCES order_items(order_item_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    resolution VARCHAR(20) NOT NULL DEFAULT 'REFUND'
        CHECK (resolution IN ('REFUND','EXCHANGE','OTHER')),
    restocked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_return_item UNIQUE(order_id, order_item_id)
);
CREATE INDEX IF NOT EXISTS idx_return_items_order ON order_return_items(order_id,id);

